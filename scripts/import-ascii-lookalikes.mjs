// ASCII lookalikes (1 for l, 0 for o, rn for m) from a confusable-vision release's in-place check: the ASCII pairs
// Unicode lists, each set between other letters in five common fonts at text size, at 1x and 2x. A pair is used when it
// is alike (strict or broad) in at least one of those ten renderings; its share is the fraction of them where it is,
// and its font is the one where it is closest. Capital-only swaps (I for l, 0 for O) are left out: a domain shows
// lowercase.
//
// Usage: node scripts/import-ascii-lookalikes.mjs [release dir]   (writes src/ascii-data.ts)

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import { join, basename } from "node:path";

const releases = new URL("../../confusable-vision/data/release/", import.meta.url).pathname;
const dir = process.argv[2] ?? join(releases, readdirSync(releases).filter((d) => /^\d{4}\.\d{2}\.\d{2}$/.test(d)).sort().at(-1));
const rows = gunzipSync(readFileSync(join(dir, "in-place.jsonl.gz"))).toString("utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));
const domainText = (s) => /^[a-z0-9]+$/.test(s);
const pairs = [];
for (const r of rows) {
  if (r.found !== "Unicode (ASCII)") continue;
  const a = String.fromCodePoint(parseInt(r.a.slice(2), 16));
  if (!domainText(a) || !domainText(r.b)) continue;
  const renderings = r.contexts.flatMap((c) => (c.dpr1 ? [c.dpr1, c.dpr2].map((d) => ({ verdict: d.verdict, context: c.context, distance: c.distance })) : []));
  const alike = renderings.filter((d) => d.verdict === "strict" || d.verdict === "broad");
  if (!alike.length) continue;
  const closest = alike.reduce((p, q) => (q.distance < p.distance ? q : p));
  // Two characters for one (rn for m) as a, the single one as b, as ascii.ts expects
  const [x, y] = r.b.length > a.length ? [r.b, a] : [a, r.b];
  pairs.push({ a: x, b: y, share: Math.round((alike.length / renderings.length) * 1000) / 1000, font: closest.context });
}
pairs.sort((p, q) => q.share - p.share || p.a.localeCompare(q.a));
writeFileSync(new URL("../src/ascii-data.ts", import.meta.url), `// Generated by scripts/import-ascii-lookalikes.mjs from confusable-vision release ${basename(dir)} (in-place.jsonl.gz). Do not edit by hand.
/** ASCII strings that pass for one another: a (one or two characters) and b (one), the share of ten renderings (five
 * common fonts at text size, at 1x and 2x) where they are alike, and the font where they are closest. */
export const ASCII_LOOKALIKES: { a: string; b: string; share: number; font: string }[] = ${JSON.stringify(pairs, null, 0).replace(/\},\{/g, "},\n  {")};
`);
console.log(`${pairs.length} ASCII pairs from ${dir}`);
for (const p of pairs) console.log(`  ${p.a} / ${p.b}: ${p.share} (${p.font})`);
