// ASCII lookalikes (l for 1, rn for m) from confusable-vision's ASCII search: the pairs that pass release 2's thresholds,
// with the share of text fonts in which each holds and the text font where it is closest.
//
// Usage: node scripts/import-ascii-lookalikes.mjs [path to ascii-sequences.jsonl]   (writes src/ascii-data.ts)

import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2] ?? new URL("../../confusable-vision/data/output/ascii-sequences.jsonl", import.meta.url).pathname;
const rows = readFileSync(src, "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l)).filter((r) => r.passes);
rows.sort((p, q) => q.textShare - p.textShare || p.a.localeCompare(q.a));
const pairs = rows.map((r) => ({ a: r.a, b: r.b, share: r.textShare, font: r.closestFonts[0] }));
writeFileSync(new URL("../src/ascii-data.ts", import.meta.url), `// Generated by scripts/import-ascii-lookalikes.mjs from confusable-vision's ASCII search. Do not edit by hand.
/** ASCII strings that pass for one another: a (one or two characters) and b (one), the share of text fonts where they
 * are alike, and the text font where they are closest. */
export const ASCII_LOOKALIKES: { a: string; b: string; share: number; font: string }[] = ${JSON.stringify(pairs, null, 0).replace(/\},\{/g, "},\n  {")};
`);
console.log(`${pairs.length} passing ASCII pairs from ${src}`);
