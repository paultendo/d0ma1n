#!/usr/bin/env node
/**
 * import-identifier-status.mjs
 *
 * Writes src/policy/identifier-status-data.ts from Unicode's IdentifierStatus.txt (UTS 39): the code points whose
 * Identifier_Status is Allowed. Chrome shows a domain label as punycode when it holds any other character
 * (https://chromium.googlesource.com/chromium/src/+/main/docs/idn.md, rule 3), so this decides the Chromium display.
 *
 * Usage:
 *   node scripts/import-identifier-status.mjs [path-to-IdentifierStatus.txt]
 *
 * Default path: ../confusable-vision/data/input/IdentifierStatus.txt
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = resolve(process.argv[2] ?? join(root, "../confusable-vision/data/input/IdentifierStatus.txt"));
const text = readFileSync(src, "utf8");
const date = text.match(/^# Date: (\S+)/m)?.[1] ?? "unknown";

const ranges = [];
for (const raw of text.split("\n")) {
  const line = raw.split("#")[0].trim();
  if (!line) continue;
  const [range, status] = line.split(";").map((s) => s.trim());
  if (status !== "Allowed") continue;
  const [a, b] = range.split("..");
  const first = parseInt(a, 16), last = parseInt(b ?? a, 16);
  const prev = ranges.at(-1);
  if (prev && first === prev[1] + 1) prev[1] = last;
  else ranges.push([first, last]);
}

writeFileSync(join(root, "src/policy/identifier-status-data.ts"), [
  "// Generated by scripts/import-identifier-status.mjs from Unicode IdentifierStatus.txt. Do not edit by hand.",
  `// IdentifierStatus.txt dated ${date}: code points whose Identifier_Status is Allowed, as [first, last] ranges.`,
  `export const IDENTIFIER_ALLOWED: Array<[number, number]> = ${JSON.stringify(ranges)};`,
  "",
].join("\n"));
console.log(`${ranges.length} Allowed ranges from ${src}`);
