// Multi-label public suffixes (co.uk, co.za, com.au, the Japanese prefectures and so on) from the ICANN section of the
// Public Suffix List, so a domain splits into its registrable label and its suffix: bank.co.za is "bank" under co.za,
// not "bank.co" under za. Private-section entries (github.io, blogspot.com) are left out: those are registrable
// domains in their own right, and a lookalike of one is registered at the TLD.
//
// Usage: node scripts/import-public-suffixes.mjs   (writes src/suffix-data.ts)

import { writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";

const URL_PSL = "https://publicsuffix.org/list/public_suffix_list.dat";
const text = await (await fetch(URL_PSL)).text();
const icann = text.split("===BEGIN ICANN DOMAINS===")[1].split("===END ICANN DOMAINS===")[0];

const exact = new Set(), wildcard = new Set(), exceptions = new Set();
for (const raw of icann.split("\n")) {
  const line = raw.trim();
  if (!line || line.startsWith("//")) continue;
  if (line.startsWith("!")) { exceptions.add(domainToASCII(line.slice(1))); continue; }
  if (line.startsWith("*.")) { wildcard.add(domainToASCII(line.slice(2))); continue; }
  const ascii = domainToASCII(line);
  if (ascii && ascii.includes(".")) exact.add(ascii);
}

const list = (s) => JSON.stringify([...s].sort());
writeFileSync(new URL("../src/suffix-data.ts", import.meta.url), `// Generated by scripts/import-public-suffixes.mjs from the ICANN section of the Public Suffix List.
// Do not edit by hand.
export const SUFFIXES_FETCHED = ${JSON.stringify(new Date().toISOString().slice(0, 10))};
/** Public suffixes of two or more labels, in ASCII form. */
export const MULTI_SUFFIXES: string[] = ${list(exact)};
/** Suffixes under which every label is itself a suffix (*.ck in the list). */
export const WILDCARD_SUFFIXES: string[] = ${list(wildcard)};
/** Exceptions to the wildcards (!www.ck). */
export const SUFFIX_EXCEPTIONS: string[] = ${list(exceptions)};
`);
console.log(`${exact.size} multi-label suffixes, ${wildcard.size} wildcards, ${exceptions.size} exceptions`);
