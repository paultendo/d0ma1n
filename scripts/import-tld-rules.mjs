#!/usr/bin/env node
/**
 * import-tld-rules.mjs
 *
 * Writes src/policy/repertoire-data.ts from confusable-vision's data/input/tld-rules.json: which characters each TLD's
 * registry accepts at the second level. confusable-vision owns the rules (scripts/build-tld-rules.py there, from the
 * IANA IDN tables, the root zone database and researched country-code policies), so its releases and this scanner
 * judge registrability the same way.
 *
 * Usage:
 *   node scripts/import-tld-rules.mjs [path-to-tld-rules.json]
 *
 * Default path: ../confusable-vision/data/input/tld-rules.json
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = resolve(process.argv[2] ?? join(root, "../confusable-vision/data/input/tld-rules.json"));
const data = JSON.parse(readFileSync(src, "utf8"));

const out = [
  "// Generated by scripts/import-tld-rules.mjs from confusable-vision data/input/tld-rules.json. Do not edit by hand.",
  `// IANA IDN tables and root zone database fetched ${data.fetched}; country-code registry policies and corrections`,
  "// from confusable-vision data/input/cctld-idn-rules.json and tld-overrides.json.",
  "//",
  "// TLD_TABLES lists each distinct repertoire as hex code point ranges beyond ASCII (\"CJK\" stands for the",
  "// ideographs and Hangul syllables a table lists). TLD_RULES maps a TLD (ASCII form) to the tables a label",
  "// must fit one of, or \"ascii\" when the registry takes ASCII only. A TLD missing from TLD_RULES is unknown.",
  `export const TLD_RULES_FETCHED = ${JSON.stringify(data.fetched)};`,
  `export const TLD_TABLES: string[] = ${JSON.stringify(data.tables)};`,
  `export const TLD_RULES: Record<string, number[] | "ascii"> = ${JSON.stringify(data.rules)};`,
  "/** Country-code TLDs whose rules are unknown, assumed ASCII-only until checked. */",
  `export const TLD_ASSUMED_ASCII: string[] = ${JSON.stringify(data.assumedAscii)};`,
  "/** Where a rule came from, for TLDs not covered by the IANA repository or the ICANN agreement. */",
  `export const TLD_RULE_SOURCES: Record<string, string> = ${JSON.stringify(data.ruleSources, null, 1)};`,
  "",
].join("\n");
writeFileSync(join(root, "src/policy/repertoire-data.ts"), out);
console.log(`${Object.keys(data.rules).length} TLDs from ${src}`);
